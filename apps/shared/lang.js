const DICTS = { en, am, ti, om };

function translate(lang, key, vars) {
  const raw = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
}

const I18nContext = createContext({ lang: 'en', setLang: () => {}, t: (k) => k });

const initialLang = () => {
  const stored = getPref(PREF.lang);
  return LANGS.some((l) => l.code === stored) ? stored : 'en';
};

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);

  useEffect(() => onPrefsChange(() => setLangState(initialLang())), []);

  const setLang = useCallback((code) => {
    if (!LANGS.some((l) => l.code === code)) return;
    setLangState(code);
    setPref(PREF.lang, code);
  }, []);

  const value = useMemo(() => {
    const t = (key, vars) => translate(lang, key, vars);
    return { lang, setLang, t };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

